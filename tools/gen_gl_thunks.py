#!/usr/bin/env python3
"""Generate peload/gl_thunks.h: one Windows-convention wrapper per OpenGL entry
point, calling the host's own GL through a pointer.

A plug-in calls OpenGL with the Windows calling convention -- ms_abi on x86-64,
stdcall on i386 -- and the host's libGL takes System V arguments. Which register
an argument travels in depends on every argument before it, so a wrapper has to
know the full signature; this reads the signatures from the Khronos headers
rather than writing two thousand of them by hand.

    tools/gen_gl_thunks.py [/usr/include/GL] > peload/gl_thunks.h

The output is checked in, so a build needs no GL headers at all.
"""
import os, re, sys

INC = sys.argv[1] if len(sys.argv) > 1 else '/usr/include/GL'

# Every GL type, as the explicit-width C type it is on Windows and Linux alike.
TYPES = {
    'void': 'void',
    'GLenum': 'uint32_t', 'GLbitfield': 'uint32_t', 'GLuint': 'uint32_t',
    'GLint': 'int32_t', 'GLsizei': 'int32_t', 'GLfixed': 'int32_t',
    'GLclampx': 'int32_t', 'GLhandleARB': 'uint32_t',
    'GLboolean': 'uint8_t', 'GLubyte': 'uint8_t', 'GLbyte': 'int8_t',
    'GLchar': 'char', 'GLcharARB': 'char',
    'GLshort': 'int16_t', 'GLushort': 'uint16_t', 'GLhalf': 'uint16_t',
    'GLhalfARB': 'uint16_t', 'GLhalfNV': 'uint16_t',
    'GLfloat': 'float', 'GLclampf': 'float',
    'GLdouble': 'double', 'GLclampd': 'double',
    'GLintptr': 'intptr_t', 'GLsizeiptr': 'intptr_t',
    'GLintptrARB': 'intptr_t', 'GLsizeiptrARB': 'intptr_t',
    'GLvdpauSurfaceNV': 'intptr_t',
    'GLint64': 'int64_t', 'GLuint64': 'uint64_t',
    'GLint64EXT': 'int64_t', 'GLuint64EXT': 'uint64_t',
    'GLsync': 'void *', 'GLeglImageOES': 'void *', 'GLeglClientBufferEXT': 'void *',
}
# Arguments that are a function the GL calls back. The callback is the
# plug-in's, in the Windows convention, and the host's GL would call it as
# System V: these are accepted and not passed on.
CALLBACKS = ('GLDEBUGPROC', 'GLDEBUGPROCARB', 'GLDEBUGPROCKHR', 'GLDEBUGPROCAMD',
             'GLVULKANPROCNV')

PROTO = re.compile(r'\bGLAPI\s+([^;(]+?)\s*\b(?:GLAPIENTRY|APIENTRY)\s+(\w+)\s*\(([^;]*?)\)\s*;')


def ctype(decl):
    """The C type of one parameter or return declaration, or None if unknown."""
    d = decl.replace('const', ' ').strip()
    stars = d.count('*')
    d = d.replace('*', ' ')
    words = [w for w in d.split() if w not in ('struct',)]
    if not words:
        return None
    base = words[0]
    if stars:
        return 'void *'
    if base in CALLBACKS:
        return 'CALLBACK'
    return TYPES.get(base)


def params(argstr):
    argstr = argstr.strip()
    if argstr in ('', 'void'):
        return []
    out = []
    for p in argstr.split(','):
        p = p.strip()
        # Drop the parameter name: the last identifier, unless the whole thing
        # is a bare type.
        m = re.match(r'^(.*?)(\w+)\s*(\[\d*\])?$', p)
        if m and m.group(1).strip() and m.group(1).strip() not in ('const', 'struct'):
            t, arr = m.group(1), m.group(3)
        else:
            t, arr = p, None
        ty = ctype(t + (' *' if arr else ''))
        if ty is None:
            return None
        out.append(ty)
    return out


def main():
    seen = {}
    core = set()
    for hdr in ('gl.h', 'glext.h'):
        try:
            text = open(os.path.join(INC, hdr)).read()
        except OSError:
            continue
        text = re.sub(r'\s+', ' ', text)           # a prototype may span lines
        for m in PROTO.finditer(text):
            ret, name, args = m.group(1), m.group(2), m.group(3)
            if name in seen:
                continue
            rt = ctype(ret)
            ps = params(args)
            if rt is None or ps is None or rt == 'CALLBACK':
                continue
            seen[name] = (rt, ps)
            if hdr == 'gl.h':
                core.add(name)
    # opengl32.dll exports OpenGL 1.1 and nothing later: everything newer is
    # only ever reached through wglGetProcAddress, and a plug-in that imports
    # it by name would not load on Windows either.
    core = {n for n in core if n in GL11}
    names = sorted(seen)
    w = sys.stdout.write
    w('/* Generated by tools/gen_gl_thunks.py from the Khronos GL headers. Do not\n'
      ' * edit: regenerate. %d entry points, %d of them exported by opengl32. */\n'
      % (len(names), len(core)))
    w('#ifndef PELOAD_GL_THUNKS_H\n#define PELOAD_GL_THUNKS_H\n\n')
    w('#define GLT_N %d\n' % len(names))
    w('static void *glt_fn[GLT_N];\n\n')
    for i, n in enumerate(names):
        rt, ps = seen[n]
        real = [p for p in ps if p != 'CALLBACK']
        decl = ', '.join('%s a%d' % (p if p != 'CALLBACK' else 'void *', k)
                         for k, p in enumerate(ps)) or 'void'
        call_t = ', '.join(real) or 'void'
        call_a = ', '.join('a%d' % k for k, p in enumerate(ps) if p != 'CALLBACK')
        unused = ''.join(' (void)a%d;' % k for k in range(len(ps)))
        if 'CALLBACK' in ps:
            # Registering a Windows-convention callback with the host's GL
            # would have it called with the wrong registers. Not registering
            # it loses only the debug output it was for.
            body = '{%s %s}' % (unused, 'return 0;' if rt != 'void' else '')
        elif rt == 'void':
            body = '{ if (glt_fn[%d]) ((void (*)(%s))glt_fn[%d])(%s); }' % (i, call_t, i, call_a)
        else:
            body = '{ return glt_fn[%d] ? ((%s (*)(%s))glt_fn[%d])(%s) : (%s)0; }' % (
                i, rt, call_t, i, call_a, rt)
        w('static MS %s st_%s(%s)\n%s\n' % (rt, n, decl, body))
    w('\nstatic const struct { const char *name; void *fn; uint8_t core; } glt_tab[GLT_N] = {\n')
    for n in names:
        w('    { "%s", (void *)st_%s, %d },\n' % (n, n, 1 if n in core else 0))
    w('};\n\n')
    w('#define GLT_STUB_ENTRIES \\\n')
    for n in sorted(core):
        w('    S("opengl32.dll", %s), \\\n' % n)
    w('\n#endif /* PELOAD_GL_THUNKS_H */\n')


